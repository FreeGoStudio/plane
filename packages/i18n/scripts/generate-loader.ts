import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../src/locales");
const entries = fs
  .readdirSync(root)
  .toSorted()
  .flatMap((language) =>
    fs
      .readdirSync(path.join(root, language))
      .filter((file) => file.endsWith(".json"))
      .toSorted()
      .map(
        (file) =>
          `  ${JSON.stringify(`${language}/${file.slice(0, -5)}`)}: () => import(${JSON.stringify(`./locales/${language}/${file}`)}),`
      )
  );
const source = `// Generated by scripts/generate-loader.ts. Static imports make locale chunks portable across bundlers and Windows.
const loaders: Record<string, () => Promise<{ default: Record<string, unknown> }>> = {
${entries.join("\n")}
};

export function loadLocale(language: string, namespace: string) {
  const loader = loaders[language + "/" + namespace];
  if (!loader) return Promise.reject(new Error("Unsupported locale resource: " + language + "/" + namespace));
  return loader();
}
`;
fs.writeFileSync(path.resolve(import.meta.dirname, "../src/load-locale.ts"), source);
